def играть_уровень(номер, уровень):
    заголовок(уровень["название"])
    рассказ(уровень["текст"])

    комната = list(уровень["предметы"])
    препятствия = dict(уровень["препятствия"])

    while игрок["жизни"] > 0:
        показать_меню(МЕНЮ_УРОВНЯ)
        пункт = спросить_номер(len(МЕНЮ_УРОВНЯ))

        if пункт == 0:
            continue
        elif пункт == 1:
            print("Предметы вокруг:", ", ".join(комната) if комната else "ничего")
            print("Препятствия:", ", ".join(препятствия) if препятствия else "нет")
        elif пункт == 2:
            предмет = выбрать_предмет(комната, "Что взять?")
            if предмет:
                взять(предмет, комната)
        elif пункт == 3:
            предмет = выбрать_предмет(игрок["инвентарь"], "Что использовать?")
            if предмет:
                использовать(предмет, препятствия, уровень["победа"])
        elif пункт == 4:
            предмет = выбрать_предмет(игрок["инвентарь"], "Что осмотреть?")
            if предмет:
                осмотреть_предмет(предмет)
        elif пункт == 5:
            показать_инвентарь()
        elif пункт == 6:
            показать_статус()
        elif пункт == 7:
            показать_журнал()
        elif пункт == 8:
            показать_карту()
        elif пункт == 9:
            показать_подсказку(номер)
        elif пункт == 10:
            показать_правила()
        elif пункт == 11:
            нет = проверить_обязательное(уровень["обязательно"])
            if препятствия:
                print("Путь закрыт:", ", ".join(препятствия))
            elif нет:
                print("Без этого уходить нельзя:", ", ".join(нет))
            else:
                print("Уровень пройден!")
                игрок["пройдено"].add(номер)
                return True
    return False


def задать_загадку(вопрос, ответ, цифра, цифры):
    print("\nЭн:", вопрос)
    for попытка in range(2):
        текст = input("Ято: ").strip().lower()
        if ответ in текст:
            print("Эн кивает: «Верно». Он записывает цифру на листке:", цифра)
            игрок["алиби"].add(ответ)
            записать("Верно решил загадку: " + ответ)
            цифры.append(цифра)
            return True
        if попытка == 0:
            print("Эн: «Подумай ещё».")
    print("Эн: «Неверно». Он убирает листок.")
    игрок["подозрение"] += 1
    игрок["улики"].add("не смог ответить на загадку: " + ответ)
    return False


