def спросить_номер(количество):
    ввод = input("Выбери номер: ").strip()
    if ввод.isdigit() and 1 <= int(ввод) <= количество:
        return int(ввод)
    print("Введи число от 1 до " + str(количество) + ".")
    return 0


def выбрать_предмет(список, вопрос):
    if not список:
        print("Выбирать не из чего.")
        return ""
    print("\n" + вопрос)
    for номер, вещь in enumerate(список, 1):
        print(str(номер) + ". " + вещь)
    print("0. Назад")
    ввод = input("Выбери номер: ").strip()
    if ввод.isdigit() and 1 <= int(ввод) <= len(список):
        return список[int(ввод) - 1]
    return ""


